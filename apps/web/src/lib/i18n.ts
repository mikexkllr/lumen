export type TKey = Key;

export function translate(locale: UiLocale, key: TKey, vars?: Record<string, string | number>): string {
  const dict = locale === 'en' ? en : (de as Record<Key, string | readonly string[]>);
  let s = dict[key] ?? de[key];
  if (Array.isArray(s)) s = s[Math.floor(Math.random() * s.length)];
  let out = s as string;
  // plural forms: [[n:Tag|Tage]] (may contain {vars})
  out = out.replace(/\[\[(\w+):([^|\]]*)\|([^\]]*)\]\]/g, (_, k: string, one: string, many: string) => (Number(vars?.[k]) === 1 ? one : many));
  for (const [k, v] of Object.entries(vars ?? {})) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function detectLocale(): UiLocale {
  const l = typeof navigator !== 'undefined' ? navigator.language : 'de';
  return l.toLowerCase().startsWith('de') ? 'de' : 'en';
}

/** All UI string keys (for tests and tooling). */
export const allKeys = (): TKey[] => Object.keys(de) as TKey[];

/** The untranslated source of a key: a string or a list of variants. */
export function rawString(locale: UiLocale, key: TKey): string | readonly string[] {
  return (locale === 'en' ? en : (de as Record<Key, string | readonly string[]>))[key];
}
